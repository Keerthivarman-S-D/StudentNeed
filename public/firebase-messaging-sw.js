const messaging = firebase.messaging();

// 4. Background message handler for FCM payloads
messaging.onBackgroundMessage((payload) => {
  // If the payload already contained a top-level 'notification' object,
  // Firebase Messaging Compat automatically renders the system notification.
  // Avoid creating a duplicate notification banner!
  if (payload.notification) {
    return;
  }

  // Handle data-only messages or custom payloads
  const data = payload.data || {};
  const notificationTitle = data.title || 'StudentNeed';
  const targetChatId = data.chatId;
  const targetUrl = data.url || data.link || (targetChatId ? `/chat/${targetChatId}` : '/');

  const notificationOptions = {
    body: data.body || 'New campus update.',
    icon: data.icon || '/studentneed-monogram.png',
    badge: data.badge || '/favicon.png',
    tag: data.tag || (targetChatId ? `chat_${targetChatId}` : 'studentneed_fcm'),
    renotify: true,
    data: {
      url: targetUrl,
      chatId: targetChatId,
      reservationId: data.reservationId,
      targetType: data.targetType,
      targetId: data.targetId,
      timestamp: Date.now()
    },
    vibrate: [120, 60, 120]
  };

  return self.registration.showNotification(notificationTitle, notificationOptions);
});

// 5. Standard Web Push event listener for VAPID-based payloads
self.addEventListener('push', (event) => {
  if (!event.data) return;

  let payload = {};
  try {
    payload = event.data.json();
  } catch (err) {
    payload = {
      title: 'StudentNeed',
      body: event.data.text() || 'New campus update.',
    };
  }

  // If this push was generated by Firebase FCM SDK (contains fcmMessageId, from, or notification),
  // let Firebase Messaging compat handle it to avoid duplicate notification banners.
  if (payload.fcmMessageId || payload.from || payload.notification) {
    return;
  }

  const title = payload.title || 'StudentNeed';
  const data = payload.data || {};
  const targetChatId = data.chatId;
  const targetUrl = payload.url || data.url || (targetChatId ? `/chat/${targetChatId}` : '/');

  // Foreground suppression:
  // If the user already has StudentNeed open, focused, and is viewing the EXACT conversation,
  // do not produce a redundant OS-level notification banner.
  const checkActiveClients = self.clients
    .matchAll({ type: 'window', includeUncontrolled: true })
    .then((clientList) => {
      if (targetChatId && clientList.length > 0) {
        const isViewingExactChat = clientList.some((client) => {
          return (
            client.focused &&
            client.visibilityState === 'visible' &&
            client.url.includes(`/chat/${targetChatId}`)
          );
        });

        if (isViewingExactChat) {
          return;
        }
      }

      const options = {
        body: payload.body || 'You received a new campus notification.',
        icon: payload.icon || '/studentneed-monogram.png',
        badge: payload.badge || '/favicon.png',
        tag: payload.tag || (targetChatId ? `chat_${targetChatId}` : 'studentneed_push'),
        renotify: true,
        data: {
          url: targetUrl,
          chatId: targetChatId,
          timestamp: Date.now(),
        },
        vibrate: [120, 60, 120],
      };

      return self.registration.showNotification(title, options);
    });

  event.waitUntil(checkActiveClients);
});

// 6. Notification click navigation handler
self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const targetUrl = event.notification.data?.url || event.notification.data?.link || '/';

  const navigateToClient = self.clients
    .matchAll({ type: 'window', includeUncontrolled: true })
    .then((clientList) => {
      // If a StudentNeed tab is already open, focus it and navigate
      for (const client of clientList) {
        if ('focus' in client) {
          client.focus();
          if ('navigate' in client) {
            return client.navigate(targetUrl);
          }
          return;
        }
      }
      // Otherwise open a new window
      if (self.clients.openWindow) {
        return self.clients.openWindow(targetUrl);
      }
    });

  event.waitUntil(navigateToClient);
});
